import { readFile, writeFile, copyFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import "./sync-brand.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
const themePath = new URL("../packages/ui/src/themes.json", import.meta.url);
const themes = JSON.parse(await readFile(themePath, "utf8"));
const css = Object.entries(themes).map(([name, values]) => {
  const selector = name === "light" ? ':root, [data-hulmio-theme="light"]' : `[data-hulmio-theme="${name}"]`;
  return `${selector} {\n${Object.entries(values).map(([key, value]) => `  --hulmio-${key}: ${value};`).join("\n")}\n}`;
}).join("\n");
await writeFile(new URL("../packages/ui/src/tokens.css", import.meta.url), `/* Generated by npm run build:ui from themes.json. */\n${css}\n`);

for (const args of [
  ["node_modules/vite/bin/vite.js", "build", "--config", "packages/ui/vite.config.ts"],
  ["node_modules/typescript/bin/tsc", "-p", "packages/ui/tsconfig.build.json"],
]) {
  const result = spawnSync(process.execPath, args, { cwd: root, stdio: "inherit" });
  if (result.error) throw result.error;
  if (result.status !== 0) process.exit(result.status ?? 1);
}

// Declaration-only tsc does not copy JSON assets; keep public theme types resolvable.
await copyFile(themePath, new URL("../packages/ui/dist/types/src/themes.json", import.meta.url));
const declarationPath = new URL("../packages/ui/dist/types/src/index.d.ts", import.meta.url);
await writeFile(declarationPath, (await readFile(declarationPath, "utf8")).replace(/^import "\.\/styles\.css";\r?\n/m, ""));
